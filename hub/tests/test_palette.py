"""Палитра «Созвездие» — проектное решение, которое должно пережить правки.

Цвет — не то значение, которое кто-то вспомнит проверить. Акцент жил в шести
файлах и заменялся руками; без теста следующий человек добавит правило старым
цветом, и никто об этом не скажет.

Здесь проверяется не «цвет на месте», а свойства, которые делают палитру
связной. Их шесть:

* **один источник.** Значение лежит в `base.css`. Страницы не объявляют своих
  цветов — иначе мы снова получим пять копий, которые разойдутся, и именно так
  уже пропал `--danger`: правило `.error` ссылалось на переменную, которой не
  было ни в одной копии, CSS молча инвалидировался, и ошибка входа не
  окрашивалась никогда;

* **ночь, а не бумага.** Фон почти чёрный и синеватый. Прежняя (светлая)
  палитра изображала реестр бумагой с ink-контрастом 15:1 на мягком фоне —
  решение было честным для реестра, но владелец выбрал иначе: направление
  «Созвездие» из docs/design — тёмный премиум-интерфейс с картой узлов.
  Тест требует тёмный фон и светлый текст и ловит возврат к светлой теме
  численно;

* **два сигнала с разными обязанностями.** Синий `--sig` и `--sig-deep` —
  голос бренда: кнопка, фокус, активная ссылка, знак. Зелёный `--live`
  и `--live-fill` — вердикт: узел прошёл проверку. Каждый отвечает за своё:
  зелёный шапкой نیست; всё остальное — отступы и нейтраль. warn/fail
  объявлены, но появляются только в состоянии отказа — их отсутствие на
  экране и есть норма;

* **фон нейтрален.** У ночного неба есть синеватый уклон (нейтраль бренда),
  но не цвет: поверхность с заметным зелёным или иным оттенком спорила бы со
  штампом. Граница синевы — 60 единиц по разнице каналов; она охватывает
  --ink-2 (55), --ink-3 (54) и --gauge (52) и отсекает решётку сигналов
  (от 117 и выше);

* **контраст посчитан.** Каждая пара «цвет на фоне» проверена арифметически
  (относительная яркость, линеаризация sRGB), а не на глаз. Значения в
  комментариях `base.css` — не пожелание, а результат: их пересчитывает тест;

* **направление приглушения.** На тёмном фоне «тише» значит ТЕМНЕЕ. Светлая
  палитра держала `--live-fill` светлее `--live`, потому что там тише =
  светлее. Здесь наоборот, и тест требует именно темнее: иначе при переносе
  палитры «тихая» заливка стала бы такой же громкой, как штамп.
"""

from __future__ import annotations

import colorsys
import re
from pathlib import Path

#: Прежняя палитра: оранжевый акцент, его светлая бумага и кислотный акцент
#: салатового тёмной темы до неё. Литералами, потому что смысл — узнать их,
#: если они вернутся, а не описать их.
REJECTED = (
    "#e8543a",  # оранжевый акцент
    "#1a0c08",  # его фон
    "#e0a458",  # тёмно-янтарный из той же палитры
    "#b4f04a",  # кислотный салатовый
    "#81ab37",
    "#faf3e0",  # светлая бумага прежнего реестра
    "#fffaf0",
    "#282c34",  # «дашборд разработчика», сменивший бумагу
    "#abb2bf",
)

#: Единственный файл, которому позволено объявлять цвета.
TOKENS = "src/hub/ui/base.css"

#: Все страницы продукта и их собственные стили. Ни один файл здесь не должен
#: объявлять цвет сам: цвет — это палитра, а палитра одна.
SURFACES = [
    "src/hub/ui/index.html",
    "src/hub/ui/hub.css",
    "src/hub/ui/status.html",
    "src/hub/ui/status.css",
    "src/hub/ui/admin.html",
    "src/hub/ui/admin.css",
    "src/hub/ui/login.html",
    "src/hub/ui/login.css",
]

#: Цветные токены вне сигнальной пары. Появляются только при отказе: их
#: отсутствие на экране — норма. Перечислены явно, чтобы правило «два
#: сигнала» осталось правилом, а не превратилось в «сколько получилось».
FAULT_TOKENS = {"warn", "fail"}

#: Токены зелёного вердикта: сам штамп и его приглушённая плашка.
MARK_TOKENS = {"live", "live-fill"}

#: Токены синего бренда: кнопки, фокус, знак, активные ссылки.
SIGNAL_TOKENS = {"sig", "sig-deep"}

ROOT = Path(__file__).resolve().parents[1]


def _read(rel: str) -> str:
    return (ROOT / rel).read_text(encoding="utf-8")


def _without_comments(text: str) -> str:
    """Убрать `/* ... */`, чтобы упоминание цвета в объяснении не считалось его
    использованием.

    В `base.css` отвергнутые цвета названы прямо — это историческая справка о
    том, почему палитра такая, и она нужна читателю. Считать её нарушением
    значило бы запретить объяснять решение, чтобы его соблюдать.
    """
    return re.sub(r"/\*.*?\*/", "", text, flags=re.DOTALL)


def _rgb(colour: str) -> tuple[int, int, int]:
    colour = colour.lstrip("#")
    return tuple(int(colour[i : i + 2], 16) for i in (0, 2, 4))  # type: ignore[return-value]


def _luminance(colour: str) -> float:
    channels = [c / 255 for c in _rgb(colour)]
    linear = [c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4 for c in channels]
    return 0.2126 * linear[0] + 0.7152 * linear[1] + 0.0722 * linear[2]


def _ratio(a: str, b: str) -> float:
    la, lb = _luminance(a), _luminance(b)
    hi, lo = max(la, lb), min(la, lb)
    return (hi + 0.05) / (lo + 0.05)


def _hue(colour: str) -> float:
    r, g, b = (c / 255 for c in _rgb(colour))
    return colorsys.rgb_to_hsv(r, g, b)[0] * 360


def _chroma(colour: str) -> int:
    """Разница между старшим и младшим каналом. Ноль — чистый серый."""
    return max(_rgb(colour)) - min(_rgb(colour))


def _root_block() -> str:
    text = _read(TOKENS)
    match = re.search(r":root\s*\{(.*?)\n\}", text, re.DOTALL)
    assert match, "base.css has no :root block"
    return match.group(1)


def _token(name: str) -> str:
    """Значение токена из `base.css`, как `#rrggbb`."""
    match = re.search(rf"--{name}:\s*(#[0-9a-fA-F]{{6}})", _read(TOKENS))
    assert match, f"base.css declares no --{name}"
    return match.group(1).lower()


def _colour_tokens() -> dict[str, str]:
    """Все цветные токены `:root`, кроме отступов и нецветовых значений."""
    return {
        name: value
        for name, value in re.findall(r"--([a-z0-9-]+):\s*(#[0-9a-fA-F]{6})", _root_block())
    }


