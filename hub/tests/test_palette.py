def test_no_surface_uses_a_rejected_colour():
    """Ни один отвергнутый цвет не должен вернуться ни на одну поверхность."""
    offenders = []
    for rel in [TOKENS, *SURFACES]:
        text = _without_comments(_read(rel)).lower()
        for colour in REJECTED:
            if colour in text:
                offenders.append(f"{rel}: {colour}")
    assert not offenders, "отвергнутый цвет вернулся:\n" + "\n".join(offenders)


def test_the_palette_has_exactly_one_source():
    """Страницы не объявляют цветов — только `base.css`.

    Это и есть починка структурного бага: раньше `:root` с палитрой лежал в
    пяти файлах, и `--danger` пропал ровно потому, что копий было пять. Тест
    ловит не «цвет не тот», а «цвет объявлен не там», и это разные ошибки.

    Стили страниц вынесены в отдельные `.css` (`hub.css`, `status.css`, ...),
    а не лежат в `<style>` внутри html. Это не вкусовщина: `.html` со `<style>`
    заставил бы тест разбирать html регулярным выражением, и палитра,
    добавленная в такой блок, была бы невидима проверке ровно так же, как была
    невидима `--danger`.
    """
    offenders = {}
    for rel in SURFACES:
        text = _without_comments(_read(rel))
        # `theme-color` — это цвет браузерной рамки телефона, а не поверхность:
        # он обязан совпадать с --paper, но записан метатегом, который стили
        # перечитывать не умеют. Вычтена одна строка, не весь поиск.
        text = re.sub(r'<meta[^>]*theme-color[^>]*>', "", text, flags=re.S)
        found = re.findall(r"#[0-9a-fA-F]{3,8}\b", text)
        if found:
            offenders[rel] = sorted(set(found))
    assert not offenders, (
        "цвета объявлены вне base.css — палитра снова размножилась:\n"
        + "\n".join(f"  {rel}: {cols}" for rel, cols in offenders.items())
    )


def test_no_surface_declares_its_own_root_palette():
    """`<style>` внутри страницы не объявляет `:root` с цветами.

    Отдельно от предыдущего: тот ловит `#rrggbb` где угодно, а этот — саму
    привычку заводить странице собственную палитру. Страница вправе объявить
    `--col` (ширину колонки) в своём css-файле: это её решение о раскладке, а
    не о цвете.
    """
    offenders = []
    for rel in SURFACES:
        if not rel.endswith(".html"):
            continue
        html = _read(rel)
        for block in re.findall(r"<style[^>]*>(.*?)</style>", html, re.DOTALL):
            if re.search(r":root\s*\{", block):
                offenders.append(rel)
    assert not offenders, (
        "у страницы собственный блок :root — стили должны лежать в отдельном "
        f".css: {offenders}"
    )


def test_every_declared_colour_is_a_six_digit_hex():
    """Полный `#rrggbb`, без трёхзначных сокращений и без альфы.

    `#fff` и `#0af` читаются человеком хуже, а `#rrggbbaa` не поддерживается
    старыми движками — и то и другое выясняется на живом сервере.
    """
    root = _root_block()
    colours = re.findall(r"#[0-9a-fA-F]+", root)
    bad = [c for c in colours if not re.fullmatch(r"#[0-9a-fA-F]{6}", c)]
    assert not bad, f"не полные hex-значения в :root: {bad}"


