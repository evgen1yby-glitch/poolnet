def test_the_text_colours_are_readable_on_the_night():
    """WCAG AA для всего, что читается как текст.

    Посчитано, а не прикинуто на глаз: «помягче» чернила, упавшие ниже 4.5:1,
    на тёмной ночи не оттенок, а текст, который никто не прочитает.
    """
    paper = _token("paper")
    for name in ("ink", "ink-2", "sig", "sig-deep", "live", "warn", "fail"):
        ratio = _ratio(_token(name), paper)
        assert ratio >= 4.5, f"--{name} на --paper даёт {ratio:.2f}:1"


def test_the_quiet_ink_is_deliberately_quiet():
    """`--ink-3` не проходит AA — и это решение, а не недосмотр.

    Он несёт служебное: номер ступени, подпись под числом, «последний прогон».
    Поднять его до AA значило бы сделать служебное равным основному, и
    иерархия из трёх уровней превратилась бы в один. Тест пинует ИМЕННО
    приглушённость: тот, кто «починит» контраст до 4.5:1, сломает замысел, и
    это должно быть видно.
    """
    ratio = _ratio(_token("ink-3"), _token("paper"))
    assert ratio < 4.5, (
        f"--ink-3 {_token('ink-3')} даёт {ratio:.2f}:1 — он перестал быть "
        "приглушённым, и служебное теперь спорит с основным"
    )
    # Но и не исчез: ниже 2:1 текст перестаёт быть текстом.
    assert ratio >= 2.0, f"--ink-3 даёт {ratio:.2f}:1 — это уже не текст"


def test_the_fill_is_readable_against_what_sits_on_it():
    """Крупная заливка достаточно отличается от подложки дорожки.

    Заливка не несёт текста, поэтому AA «4.5:1 для текста» к ней не
    применяется. Применяется другое: полоса обязана читаться как полоса, то
    есть заметно отличаться от подложки, на которой она лежит.
    """
    ratio = _ratio(_token("live-fill"), _token("paper-2"))
    assert ratio >= 4.0, (
        f"--live-fill на подложке дорожки даёт {ratio:.2f}:1 — полоса не читается"
    )


def test_the_quiet_gauge_is_visible_but_not_loud():
    """Дорожка распределения видна на подложке, но не спорит со штампом.

    Две границы и обе нужны. Ниже 1.8:1 полоса исчезает — тогда «страна с
    тремя узлами» и «страна с тремястами» выглядят одинаково. Выше штампа она
    начала бы конкурировать с цветом состояния, который обязан оставаться
    самым заметным. Как и заливка штампа, дорожка тише штампа по ЯРКОСТИ:
    на тёмной ночи тише — значит темнее.
    """
    gauge = _ratio(_token("gauge"), _token("paper-2"))
    assert gauge >= 1.8, f"--gauge даёт {gauge:.2f}:1 — полосы не видно"
    assert _luminance(_token("gauge")) < _luminance(_token("live-fill")), (
        "--gauge светлее --live-fill и спорит с цветом состояния"
    )


