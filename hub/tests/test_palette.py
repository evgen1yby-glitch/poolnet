def test_every_colour_token_is_declared_and_used():
    """Объявленный токен используется, использованный — объявлен.

    Две ошибки одного рода: мёртвое значение в палитре и ссылка на
    несуществующее. Вторая уже случалась и стоила неработающего правила,
    поэтому проверяются обе.
    """
    declared = set(_colour_tokens())
    # Не цветные: шрифты, радиусы, ширина колонки. Объявляются в том же
    # `:root`, но к палитре не относятся.
    non_colour = {"mono", "sans", "disp", "gut", "r", "r-sm", "col", "prose"}

    used: set[str] = set()
    for rel in [TOKENS, *SURFACES]:
        for name in re.findall(r"var\(--([a-z0-9-]+)", _read(rel)):
            used.add(name)

    missing = sorted(used - declared - non_colour)
    assert not missing, f"в правилах используются необъявленные токены: {missing}"

    unused = sorted(declared - used)
    assert not unused, (
        f"эти цветные токены объявлены, но нигде не используются: {unused}"
    )


def test_inline_pages_use_the_one_palette():
    """Страницы, вшитые в `api.py`, тоже не приносят своей палитры.

    `/help` вшит в код, потому что должен открываться без сети и без файлов;
    первая версия их и принесла — свой `color-scheme: dark` и четыре
    `#rrggbb`, то есть шестую копию палитры ровно в том месте, где палитра уже
    один раз разъехалась. Страница подключает `/static/base.css` с того же
    хоста и держит у себя только раскладку.

    Проверяется сам исходник `api.py`: литерал вшитой страницы — это
    поверхность продукта, даже когда он лежит в `.py`.
    """
    source = _read("src/hub/api.py")
    for name in ("_HELP_HTML",):
        match = re.search(rf'{name} = """(.*?)"""', source, re.DOTALL)
        assert match, f"в api.py нет вшитой страницы {name}"
        markup = _without_comments(match.group(1))
        found = re.findall(r"#[0-9a-fA-F]{3,8}\b", markup)
        assert not found, f"{name} объявляет цвета: {sorted(set(found))}"
        assert "color-scheme: dark" not in markup, (
            f"{name} не возвращает тёмную тему в своих стилях"
        )
        assert 'href="/static/base.css"' in markup, (
            f"{name} не подключает палитру продукта"
        )
