def test_the_page_is_night_not_paper():
    """Фон тёмный, текст светлый — и это требование, а не вкус.

    Прежняя палитра изображала реестр бумагой. Владелец перевернул её сам:
    направление «Созвездие» выбрано из четырёх, доведено до листа и утверждено.
    Тест ловит возврат к светлой теме численно, в обе стороны: односторонняя
    проверка («фон темнее текста») прошла бы и на сером по тёмному.

    Требования в обе стороны: яркость неба должна быть меньше 0.06 (у --paper
    тут 0.003), а чернила — светлее 0.7 (у --ink 0.88).
    """
    paper = _luminance(_token("paper"))
    ink = _luminance(_token("ink"))
    assert paper < 0.06, (
        f"--paper {_token('paper')} имеет яркость {paper:.2f}: это ночное небо, "
        "а не осветлённая бумага"
    )
    assert ink > 0.7, (
        f"--ink {_token('ink')} имеет яркость {ink:.2f}: текст на ночи — светлый, "
        "иначе страница читается тёмным экраном без контента"
    )
    # И разница обязана быть большой: «темнее на оттенок» — это не контраст.
    assert _ratio(_token("ink"), _token("paper")) >= 12, (
        f"контраст неба и чернил {_ratio(_token('ink'), _token('paper')):.1f}:1 "
        "— недостаточен для основного текста документа"
    )


def test_the_surfaces_are_three_levels_of_night():
    """Три уровня фона, и каждый — чуть светлее предыдущего.

    Небо, утопленная полоса и приподнятое стекло — единственные три
    поверхности. Порядок важен: стекло, приподнятое над подложкой, светлее её —
    иначе подложка сериализует стеклом, и интерфейс теряет глубину.
    """
    paper = _luminance(_token("paper"))
    paper_2 = _luminance(_token("paper-2"))
    paper_3 = _luminance(_token("paper-3"))
    assert paper < paper_2 < paper_3, (
        f"уровни ночи перепутаны: {paper:.4f} < {paper_2:.4f} < {paper_3:.4f} "
        "ожидалось, но порядок другой"
    )


def test_the_night_is_blue_tinted_not_coloured():
    """У ночи синеватый уклон, но не цвет.

    Тёмная палитра с удовольствием скатывается в цветной фон, который спорит
    со штампом. Уклон — нейтраль бренда: у уровней ночи он есть и у текста
    вторых уровней, и его граница — 60 единиц разницы каналов: выше начинается
    не нейтраль, а второй сигнал.
    """
    offenders = []
    for name, value in _colour_tokens().items():
        if name in MARK_TOKENS or name in FAULT_TOKENS or name in SIGNAL_TOKENS:
            continue
        c = _chroma(value)
        if c > 60:
            offenders.append(f"--{name}: {value} (разница каналов {c})")
    assert not offenders, (
        "поверхность получила цветовой уклон, и сигнал из-за него перестанет "
        "быть сигналом:\n" + "\n".join(offenders)
    )


