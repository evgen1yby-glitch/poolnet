def test_there_are_exactly_two_signals():
    """Ровно два цветных набора: синий бренда и зелёный вердикта.

    Проверка по списку имён, а не по подсчёту: подсчёт сказал бы «шесть
    цветных токенов» и не отличил бы замысел (сигнал бренда + цвет состояния
    + два цвета отказа) от расползания.

    Порог 60 отделяет сигналы от ночи: у нейтрали разница каналов ≤ 55
    (--ink-2), у сигналов — 117 и больше. Порог на границе заставил бы тест
    мерить округление, а не замысел.
    """
    chromatic = {name for name, value in _colour_tokens().items() if _chroma(value) > 60}
    expected = MARK_TOKENS | FAULT_TOKENS | SIGNAL_TOKENS
    assert chromatic == expected, (
        "набор цветных токенов изменился. Ожидались синий бренда "
        f"{sorted(SIGNAL_TOKENS)}, зелёный вердикта {sorted(MARK_TOKENS)} и "
        f"цвета отказа {sorted(FAULT_TOKENS)}, а объявлены: {sorted(chromatic)}"
    )
    # И каждый набор — один тон: производные не разъезжаются.
    live_hues = [_hue(_token(n)) for n in ("live", "live-fill")]
    sig_hues = [_hue(_token(n)) for n in ("sig", "sig-deep")]
    assert max(live_hues) - min(live_hues) < 5, (
        f"производные --live разошлись по тону: {[round(h) for h in live_hues]}°"
    )
    assert max(sig_hues) - min(sig_hues) < 15, (
        f"производные --sig разошлись по тону: {[round(h) for h in sig_hues]}°"
    )


def test_the_mark_is_a_green_and_the_signal_is_a_cyan_blue():
    """Численно, а не на вкус.

    У зелёного самый большой канал — зелёный. У синего бренда тон в диапазоне
    цианового: он голос интерфейса, а не тревоги, поэтому между «прибор с
    оскорблением» и «уведомление о проверке» переключаются только местами.
    Далеко от циана — красный или оранжевый сигнал уже возлагают на кнопку
    тревогу, которую она не несёт.
    """
    r, g, b = _rgb(_token("live"))
    assert g > r and g > b, f"--live {_token('live')} не зелёный"
    for name in ("live", "live-fill"):
        hue = _hue(_token(name))
        assert 100 < hue < 175, (
            f"--{name} {_token(name)} имеет тон {hue:.0f}°: штамп должен быть "
            "лесным зелёным"
        )
    sig_hue = _hue(_token("sig"))
    assert 180 < sig_hue < 205, (
        f"--sig {_token('sig')} имеет тон {sig_hue:.0f}°: бренд — цианово-синий "
        "неба, а не тревожный цвет интерфейса"
    )


def test_the_fill_is_quieter_than_the_mark_ink():
    """Приглушение на тёмной ночи значит ТЕМНЕЕ, а не светлее.

    Это тест, который ловит перенос палитры между темами. Светлая версия
    держала `--live-fill` светлее `--live` и это было верно: на бумаге тише —
    значит светлее. На тёмном наоборот: тише — значит менее яркий.

    Тот, кто «починит» это по памяти от светлой темы, сделает заливку громче
    штампа, и иерархия перевернётся молча — полосы начнут кричать сильнее,
    чем отметка «прошёл», которую они иллюстрируют.
    """
    assert _luminance(_token("live-fill")) < _luminance(_token("live")), (
        "--live-fill светлее --live: на тёмной ночи это делает заливку "
        "громче штампа, а не тише"
    )


