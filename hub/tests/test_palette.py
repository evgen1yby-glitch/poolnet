def test_the_same_stage_is_drawn_the_same_way_on_both_pages():
    """Одна ступень воронки — одна заливка на лендинге и в панели.

    Лендинг и панель показывают ОДИН И ТОТ ЖЕ прогон проверки. Если одна
    страница заливает последнюю ступень одним цветом, а другая другим — это не
    «два оформления», а два разных показания одного прибора, и оператор с
    посетителем видят разное.

    Тест сравнивает не литералы, а значения — сменить оба разом он не
    запрещает.
    """
    landing = re.search(
        r'\.step\[data-p="1"\]\s*\.track\s*>\s*i\s*\{\s*background:\s*var\((--[a-z-]+)\)',
        _read("src/hub/ui/hub.css"),
    )
    panel = re.search(
        r'\.stage\[data-stage="http"\]\s*\.stage-track\s*>\s*i\s*\{\s*background:\s*var\((--[a-z-]+)\)',
        _read("src/hub/ui/admin.css"),
    )
    assert landing, "hub.css не заливает последнюю ступень воронки"
    assert panel, "admin.css не заливает последнюю ступень воронки"
    assert landing.group(1) == panel.group(1), (
        f"одна ступень залита по-разному: лендинг {landing.group(1)}, "
        f"панель {panel.group(1)}"
    )
    assert landing.group(1) == "--live-fill", (
        f"последняя ступень залита {landing.group(1)}: полоса 18×640px — это "
        "крупная площадь, и полный штамп на ней читается как тревога; тест "
        "требует приглушённую плашку --live-fill"
    )


