"""Расстановка подписей на карте выходов — одна на оба направления.

Зачем отдельный модуль. Обе карты ставят точку в процентах, а размер точки и
подпись — в пикселях. Пока карта широкая, это незаметно; при сужении точки
сходятся, а пиксельные подписи остаются прежними и садятся одна на другую и
на соседние точки. Направление B подписывало все 29 стран и на 623 px давало
23 наложенные пары на десктопе и 125 на телефоне — то есть подписи
перекрывали ровно то измерение, которое карта показывает.

Лечится не «подписями помельче», а отказом: подпись ставится только туда, где
она ничего не задевает. Крупные точки выбираются первыми (они важнее), каждой
пробуются четыре стороны — под точкой, над ней, справа, слева. Не нашлось
места — страна остаётся без подписи: точка видна, называет себя во всплывающей
подсказке, а полный реестр с числами стоит ниже. Молчаливая потеря подписи
лучше подписи, закрывающей чужое измерение.

Почему расстановка считается для узкого кадра, а не для широкого. Точки стоят
в процентах, поэтому на широкой карте они *разъезжаются*, а метрики подписи не
меняются. Значит место, свободное на минимальной ширине, свободно и на любой
большей; обратное неверно, и именно на этом ломалось. Поэтому
`place()` вызывается с `min_width`, а CSS показывает подписи при ширине
карточки не меньше того же числа (`@container`).
"""

from __future__ import annotations

import math

Side = str  # "b" | "t" | "r" | "l"


def place(
    points: list[tuple[str, float, float, float]],
    order: list[str],
    *,
    min_width: float,
    aspect: float,
    char_w: float,
    code_len: int = 2,
    line_h: float = 9.0,
    gap: float = 5.0,
    pad: float = 1.5,
    margin: float = 3.0,
) -> dict[str, Side]:
    """Код страны → сторона подписи, только для тех, кому хватило места.

    `points` — **все** точки карты, `(код, x%, y%, радиус_px)`: подпись не
    имеет права сесть ни на одну из них, в том числе на неподписанную.
    `order` — коды в порядке важности: первым подписывается то, что крупнее.
    Разделение нужно именно потому, что это разные множества: подписей
    двенадцать, а точек двадцать девять, и подпись, поставленная «в пустоте»
    между двенадцатью избранными, ложилась на девятнадцать остальных.

    Радиус в пикселях, потому что точки не масштабируются вместе с картой;
    `x`/`y` — проценты, как в разметке.
    """
    w = min_width
    h = w * aspect
    lw = char_w * code_len
    at = {code: (x / 100 * w, y / 100 * h, r) for code, x, y, r in points}
    dots = list(at.values())

    def free(rect: tuple[float, float, float, float]) -> bool:
        x0, x1, y0, y1 = rect
        if x0 < margin or x1 > w - margin or y0 < 2 or y1 > h - 2:
            return False
        for ox, oy, orad in dots:
            dx = max(x0 - ox, 0, ox - x1)
            dy = max(y0 - oy, 0, oy - y1)
            if math.hypot(dx, dy) < orad + pad:
                return False
        return not any(
            x0 < b[1] and b[0] < x1 and y0 < b[3] and b[2] < y1 for b in placed
        )

    placed: list[tuple[float, float, float, float]] = []
    out: dict[str, Side] = {}
    for code in order:
        if code not in at:
            continue
        px, py, r = at[code]
        slots = {
            "b": (px - lw / 2, px + lw / 2, py + r + gap, py + r + gap + line_h),
            "t": (px - lw / 2, px + lw / 2, py - r - gap - line_h, py - r - gap),
            "r": (px + r + gap, px + r + gap + lw, py - line_h / 2, py + line_h / 2),
            "l": (px - r - gap - lw, px - r - gap, py - line_h / 2, py + line_h / 2),
        }
        for side, rect in slots.items():
            if free(rect):
                placed.append(rect)
                out[code] = side
                break
    return out
