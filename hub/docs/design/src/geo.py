#: Кадр карты. Широта обрезана по 84° и −60°: выше и ниже нет ни одной точки,
#: а растянуть полюса на всю высоту значило бы отдать половину карты пустоте.
#: Ровно этот кадр использует `make_world.py`, поэтому берег и точки стоят в
#: одном масштабе: 360° на 1000 единиц по горизонтали, 144° на 400 по
#: вертикали — один градус всюду равен 2,78 единицы.
LON0, LON1 = -170.0, 190.0
LAT0, LAT1 = 84.0, -60.0


def project(code: str) -> tuple[float, float] | None:
    """Код страны → проценты от левого верхнего угла карты."""
    geo = GEO.get(code)
    if not geo:
        return None
    lon, lat = geo
    return ((lon - LON0) / (LON1 - LON0) * 100, (LAT0 - lat) / (LAT0 - LAT1) * 100)
