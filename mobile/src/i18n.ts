const dictionaries: Record<Lang, Record<string, string>> = { ru, en };

export function translate(lang: Lang, key: keyof typeof ru, vars?: Record<string, string | number>): string {
  let text = dictionaries[lang][key] ?? ru[key] ?? String(key);
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}
